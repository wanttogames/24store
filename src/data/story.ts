export function storyEncounter(day: number): Encounter {
  const lines = [
    "생수 한 병 주세요.",
    "어제와 같은 걸로 주세요.",
    "오늘도 같은 시간이네요.",
    "그 사람 말은 다 믿지 마세요.",
    "혹시 오래된 기사를 보셨나요?",
    "오늘은 혼자 온 게 아니에요.",
    "오늘은 계산 안 해줘도 돼요.",
  ];
  const views = [
    "회색 코트의 여자. 영상과 실제 모습이 같다.",
    "어제와 같은 옷. 손목에 화상 자국이 있다.",
    "실제로 젖은 코트. 영상 속에는 오래된 직원 명찰이 보인다.",
    "영상의 시간만 1998.03.17로 바뀐다.",
    "그녀가 과거의 계산대에 서 있다. 손에 물 한 병.",
    "그녀 뒤에 검은 그림자가 있다. 실제 매장에는 그녀만 있다.",
    "그녀는 출입문을 보고 있다. 검은 그림자가 계산대 뒤에 남는다.",
  ];
  return {
    id: "woman",
    kind: "story",
    customer: "woman",
    products: ["water"],
    minute: 197,
    line: lines[day - 1],
    look:
      day === 1
        ? "회색 코트의 평범한 여자."
        : `매일 같은 코트. ${day >= 3 ? "목에 오래된 직원 명찰 자국이 있다." : "오른쪽 소매에 물기가 있다."}`,
    productClue:
      day >= 5
        ? "생수 라벨 뒤: 「마지막 계산을 마치면 돌아갈 수 있다」."
        : "생수 한 병. 바코드와 가격은 정상.",
    cctv: views[day - 1],
    correct: day === 7 ? ["release"] : ["pay"],
    extra: day === 7 ? ["release", "lock"] : day === 6 ? ["replay"] : undefined,
    result:
      day === 7
        ? "그녀는 영수증 대신 고개를 숙였다. 잠시 뒤, 냉장고 소리가 돌아왔다."
        : "그녀는 생수를 들고 나갔다. 시계는 03:18을 가리킨다.",
  };
}
